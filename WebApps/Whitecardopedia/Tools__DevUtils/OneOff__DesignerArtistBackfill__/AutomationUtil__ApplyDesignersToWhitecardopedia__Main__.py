WCP_PROJECTS_ROOT = Path(r"D:\10_CoreLib__ValeCodebase\WebApps\Whitecardopedia\Projects")  # <-- WCP project.json root
DEFAULT_CSV_PATH  = Path(__file__).parent / "Project__Data__Query__DesignersAndArtists__.csv"   # <-- Main source CSV (co-located)
SUPPLEMENT_OUT    = Path(__file__).parent / "Project__Data__Query__Legacy2025Supplement__.csv"  # <-- Generated template / re-input (co-located)
